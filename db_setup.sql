--     2. Click the "Import" tab (top level, no database selected)
--     3. Choose this file -> click Go
--     4. Then open install.php once so the demo passwords are
--        (re)generated by PHP and verified.
--
--  Seed data uses dates RELATIVE TO TODAY, so "upcoming events"
--  is never empty no matter when the project is marked.
--
--  NOTE: keep every statement ending in a semicolon, and use ''
--  (two single quotes) for apostrophes inside text. The installer
--  splits this file on semicolons.
